import SwiftUI

/// 앱 전 화면이 공유하는 **종이 캔버스 한 장**(§2.3·§13.2) — 크림 단색.
///
/// **왜 색면 하나인가.** 이 자리는 원래 블러 80~90짜리 컬러 블롭 3장 + 글래스 프로스트 +
/// 상하 흰 시노였다. 걷어낸 근거는 취향이 아니라 **정합성**이다: 앱의 나머지 바탕은 전부 순수
/// `canvas`다 — 루트(`RootTabView`), 시트들의 `presentationBackground(ReffiColor.canvas)`,
/// To buy의 `dockedCTA(over: ReffiColor.canvas)`, 냉장고 하단 마스크. 다섯 화면만 틴트 + 프로스트
/// 면을 깔면 그 둘이 만나는 경계마다 톤이 갈린 띠가 남고, 실제로 남았다(To buy 하단 CTA 페이드가
/// 수렴하는 색이 주변과 달랐고, 냉장고 하단 마스크는 세 번째 블롭을 지워 화면 아래 142pt를
/// 다른 배경으로 만들었다). **바탕을 하나로 되돌리면 그 이음매들은 고칠 대상이 사라진다.**
///
/// **화면을 한 몸으로 묶는 것은 색면이 아니라 같은 크림 한 장이다.** 블롭은 화면마다 다른
/// accent를 받았는데 `RootTabView.pane`은 애니메이션 없는 `.opacity` 즉시 전환이라, 탭을 누를
/// 때마다 화면 전체를 덮은 색이 한 프레임에 갈아탔다. 한 몸으로 보이라고 넣은 층이 정확히 그
/// 반대를 하고 있었다.
///
/// **인자를 받지 않는 것이 이 타입의 내용이다.** `accent`/`accentDeep`을 "쓰지 않지만 남겨 두는"
/// 순간 위약 API가 되고, 다음 사람이 그 인자를 근거 삼아 블롭을 조용히 되살린다. 신선도는 배경이
/// 지지 않는다 — `IngredientBadge`의 인디케이터 바와 D-N 잉크, `DDayStamp`, 냉장고 카드의 Due date
/// 색이 이미 같은 사실을 말한다(§2.5). 화면 전체를 물들이던 건 그 위에 얹힌 네 번째 사본이었다.
/// 배경이 지는 유일한 사실은 메인의 **오늘 만료 웜톤 시노**(`MainView.background(_:)`) 하나이고,
/// 그건 신선도 3색이 아니라 "오늘이 있다/없다" 이진값이라 바탕색이 튀지 않는다.
///
/// **Reduce Transparency 분기도 함께 걷었다.** 옛 구현의 `accessibilityReduceTransparency` 게이트는
/// "켜면 블롭·시노를 걷고 캔버스만 남긴다"였는데 이제 그게 상시 상태라, 남기면 아무 일도 하지 않는
/// 분기가 된다. 이 삭제로 앱에서 그 환경값을 읽는 코드는 0이 된다 — **일부러 그렇게 뒀다**:
/// 남은 반투명 표면은 캡슐 네비(`RootTabView`)의 시스템 머티리얼 하나뿐이고 시스템 재질은 그
/// 설정에 스스로 불투명해진다. 손으로 그린 반투명을 다시 들이는 사람이 있다면 그때 이 게이트도
/// 같이 들어와야 한다.
///
/// **밋밋하다고 `PaperGrain`을 전면에 얹지 마라.** 그레인은 반점 밀도가 면적에 비례해서
/// (`PaperShape.swift`, 면적/38) 390×844 전면이면 프레임마다 8천 개 넘는 반점을 다시 그린다.
/// 재질이 필요하면 `PaperGlyphPile`이 쓰는 `ImageRenderer` 1회 굽기 + 크기 키 캐시 관용구로
/// 구워서 얹는다.
struct PaperCanvasBackground: View {
    var body: some View {
        ReffiColor.canvas.ignoresSafeArea()
    }
}
